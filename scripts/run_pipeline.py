#!/usr/bin/env python3
"""Orchestrate download -> prep -> trends -> overlays, with resumable steps.

Synthetic mode (default in config) runs entirely offline. Real mode requires
Earthdata Login credentials and refuses to pretend when they are absent.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import subprocess
import sys
import time
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.common.config import load_app_config, load_datasets_config  # noqa: E402

PREP = REPO_ROOT / "src" / "skills" / "prep_cube.py"
TRENDS = REPO_ROOT / "src" / "skills" / "compute_trends.py"
DOWNLOAD = REPO_ROOT / "src" / "skills" / "download_granules.py"
OVERLAYS = REPO_ROOT / "scripts" / "export_overlays.py"


def log(message: str) -> None:
    print(f"[pipeline] {message}", flush=True)


def run(cmd: list[str], *, cwd: Path = REPO_ROOT) -> None:
    log("$ " + " ".join(str(c) for c in cmd))
    subprocess.run(cmd, cwd=cwd, check=True)


def git_commit() -> dict[str, Any]:
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], cwd=REPO_ROOT,
            capture_output=True, text=True, check=True,
        ).stdout.strip()
        dirty = bool(subprocess.run(
            ["git", "status", "--porcelain"], cwd=REPO_ROOT,
            capture_output=True, text=True, check=True,
        ).stdout.strip())
        return {"commit": sha, "dirty_worktree": dirty}
    except Exception:
        return {"commit": None, "dirty_worktree": None}


def dataset_attrs(var: str, cfg, datasets: dict[str, Any], synthetic: bool, source: str) -> dict[str, str]:
    meta = cfg.variables[var]
    ds_meta = datasets.get(var, {})
    attrs = {
        "synthetic": "true" if synthetic else "false",
        "display_name": meta["display_name"],
        "surface": ",".join(meta["surface"]),
        "model_based": "true" if meta["model_based"] else "false",
        "source_dataset": ds_meta.get("short_name", "synthetic generator"),
        "dataset_version": str(ds_meta.get("version", "synthetic")),
        "doi": str(ds_meta.get("doi", "n/a (synthetic)")),
        "source": source,
    }
    if ds_meta.get("model_note"):
        attrs["model_note"] = ds_meta["model_note"]
    return attrs


def prep_variable(
    var: str,
    cfg,
    datasets: dict[str, Any],
    *,
    inputs: str,
    cube: Path,
    units_op: str | None,
    synthetic: bool,
    source: str,
    force: bool,
) -> None:
    if cube.exists() and not force:
        log(f"skip prep {var}: {cube} exists")
        return
    cube.parent.mkdir(parents=True, exist_ok=True)
    attrs = dataset_attrs(var, cfg, datasets, synthetic, source)
    cmd = [
        sys.executable, str(PREP),
        "--inputs", inputs,
        "--variable", var,
        "--out", str(cube),
        "--res", str(cfg.resolution),
        "--start", cfg.period[0],
        "--end", cfg.period[1],
    ]
    if units_op:
        cmd += ["--units", units_op]
    for key, value in attrs.items():
        cmd += ["--meta", f"{key}={value}"]
    run(cmd)


def trend_variable(var: str, cfg, cube: Path, layer: Path, *, jobs: int, force: bool) -> None:
    if layer.exists() and not force:
        log(f"skip trends {var}: {layer} exists")
        return
    layer.parent.mkdir(parents=True, exist_ok=True)
    run([
        sys.executable, str(TRENDS),
        "--cube", str(cube),
        "--variable", var,
        "--out", str(layer),
        "--min-months", str(cfg.analysis["min_months"]),
        "--min-years", str(cfg.analysis["min_years"]),
        "--ok-years", str(cfg.analysis["ok_years"]),
        "--alpha", str(cfg.analysis["alpha"]),
        "--jobs", str(jobs),
    ])


def synthetic_pipeline(cfg, datasets, *, only, force, jobs, skip_overlays) -> int:
    synth_dir = cfg.data_dir("synthetic")
    manifest_path = synth_dir / "manifest.json"
    needed = [synth_dir / f"{v}.zarr" for v in cfg.mode_variables("synthetic")]
    if force or not manifest_path.exists() or not all(p.exists() for p in needed):
        run([sys.executable, str(REPO_ROOT / "scripts" / "make_synthetic_data.py"),
             "--config", str(REPO_ROOT / "config" / "app.yaml")])
    cache_dir = cfg.data_dir("data_cache") / "synthetic"
    layers_dir = cfg.layers_dir
    results = []
    for var in cfg.mode_variables("synthetic"):
        if only and var not in only:
            continue
        t0 = time.time()
        source = f"SYNTHETIC DEMO DATA generated by scripts/make_synthetic_data.py; not observations ({var})"
        prep_variable(
            var, cfg, datasets,
            inputs=str(synth_dir / f"{var}.zarr"),
            cube=cache_dir / f"{var}.zarr",
            units_op=None,
            synthetic=True,
            source=source,
            force=force,
        )
        layer = layers_dir / f"{var}_trend.zarr"
        trend_variable(var, cfg, cache_dir / f"{var}.zarr", layer, jobs=jobs, force=force)
        results.append({"variable": var, "layer": str(layer.relative_to(REPO_ROOT)),
                        "seconds": round(time.time() - t0, 1)})
    if skip_overlays:
        log("overlays skipped (--skip-overlays)")
    elif OVERLAYS.exists():
        run([sys.executable, str(OVERLAYS), "--mode", "synthetic"])
    else:
        log("overlays skipped: scripts/export_overlays.py not present yet")
    manifest = {
        "mode": "synthetic",
        "synthetic": True,
        "warning": "SYNTHETIC DEMO DATA, not real observations.",
        "created_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "provenance": git_commit(),
        "grid": {"resolution_deg": cfg.resolution},
        "period": list(cfg.period),
        "analysis": cfg.analysis,
        "results": results,
        "notes": "No NASA data were downloaded. Missing months are reported, never filled.",
    }
    layers_dir.mkdir(parents=True, exist_ok=True)
    (layers_dir / "pipeline_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    log(f"wrote {layers_dir / 'pipeline_manifest.json'}")
    print("\nSYNTHETIC DEMO DATA, not real observations.")
    return 0


def credentials_available() -> bool:
    if os.environ.get("EARTHDATA_USERNAME") and os.environ.get("EARTHDATA_PASSWORD"):
        return True
    netrc = Path.home() / ".netrc"
    if not netrc.exists():
        return False
    text = netrc.read_text(errors="ignore")
    return "urs.earthdata.nasa.gov" in text and "login" in text and "password" in text


def real_pipeline(cfg, datasets, *, only, force, jobs, skip_overlays, dry_run) -> int:
    if not dry_run and not credentials_available():
        print(
            "REAL PIPELINE NOT RUN: NASA CMR is reachable, but no Earthdata Login\n"
            "credentials were found (EARTHDATA_USERNAME/PASSWORD or ~/.netrc).\n"
            "The app remains fully functional in synthetic mode.\n\n"
            "To run this on your machine:\n"
            "  1. Create a free account at https://urs.earthdata.nasa.gov\n"
            "  2. Approve the GES DISC, LP DAAC and PO.DAAC applications\n"
            "  3. export EARTHDATA_USERNAME=... EARTHDATA_PASSWORD=...  (or use ~/.netrc)\n"
            "  4. make pipeline-real\n",
            file=sys.stderr,
        )
        return 2

    raw_root = cfg.data_dir("data_raw")
    cache_dir = cfg.data_dir("data_cache") / "real"
    layers_dir = cfg.layers_dir
    results = []
    for var in cfg.mode_variables("real"):
        if only and var not in only:
            continue
        meta = datasets.get(var)
        if not meta:
            log(f"skip {var}: no config/datasets.yaml entry")
            continue
        outdir = raw_root / var
        glob = meta.get("file_glob", "*")
        have_raw = list(outdir.glob(glob)) if outdir.exists() else []
        if dry_run:
            # Catalog search is public: no login is needed to count granules.
            run([sys.executable, str(DOWNLOAD),
                 "--short-name", meta["short_name"], "--version", meta["version"],
                 "--start", meta["download"]["start"], "--end", meta["download"]["end"],
                 "--out", str(outdir), "--dry-run"])
            continue
        if meta.get("format") == "HDF4":
            log(
                f"skip {var}: {meta['short_name']} is HDF4. Convert to NetCDF first with "
                "Harmony/rioxarray/pyhdf (see docs/NASA_DATA_GUIDE.md section 7.2), then "
                "point --inputs at the converted files."
            )
            continue
        if force or not have_raw:
            run([sys.executable, str(DOWNLOAD),
                 "--short-name", meta["short_name"], "--version", meta["version"],
                 "--start", meta["download"]["start"], "--end", meta["download"]["end"],
                 "--out", str(outdir)])
        else:
            log(f"skip download {var}: {len(have_raw)} files exist in {outdir}")
        cube = cache_dir / f"{var}.zarr"
        source = f"{meta['short_name']} v{meta['version']} ({meta['daac']})"
        prep_variable(
            var, cfg, datasets,
            inputs=str(outdir / glob),
            cube=cube,
            units_op=meta.get("units_op"),
            synthetic=False,
            source=source,
            force=force,
        )
        trend_variable(var, cfg, cube, layers_dir / f"{var}_trend.zarr", jobs=jobs, force=force)
        results.append({"variable": var, "short_name": meta["short_name"],
                        "version": meta["version"], "doi": meta["doi"]})
    if dry_run:
        log("dry run complete: searched CMR only; nothing downloaded, no layers or manifest written")
        return 0
    if skip_overlays:
        log("overlays skipped (--skip-overlays)")
    elif OVERLAYS.exists():
        run([sys.executable, str(OVERLAYS), "--mode", "real"])
    manifest = {
        "mode": "real",
        "synthetic": False,
        "created_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "provenance": git_commit(),
        "grid": {"resolution_deg": cfg.resolution},
        "period": list(cfg.period),
        "results": results,
        "note": "Verify DOIs in docs/DATA_SOURCES.md; files were downloaded by the team's credentialed run.",
    }
    layers_dir.mkdir(parents=True, exist_ok=True)
    (layers_dir / "pipeline_manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--synthetic", action="store_true", help="Run the offline synthetic pipeline (default)")
    group.add_argument("--real", action="store_true", help="Run the real NASA pipeline (needs credentials)")
    ap.add_argument("--config", default=str(REPO_ROOT / "config" / "app.yaml"))
    ap.add_argument("--datasets", default=str(REPO_ROOT / "config" / "datasets.yaml"))
    ap.add_argument("--only", default=None, help="Comma-separated variable keys")
    ap.add_argument("--force", action="store_true", help="Recompute finished steps")
    ap.add_argument("--jobs", type=int, default=min(8, os.cpu_count() or 1),
                    help="Process workers for the per-cell trend loop")
    ap.add_argument("--skip-overlays", action="store_true")
    ap.add_argument("--dry-run", action="store_true", help="Real mode: only search/download dry-run")
    args = ap.parse_args()

    cfg = load_app_config(args.config)
    datasets = load_datasets_config(args.datasets)
    only = {v.strip() for v in args.only.split(",") if v.strip()} if args.only else None
    real = args.real or (not args.synthetic and cfg.mode == "real")
    log(f"mode={'real' if real else 'synthetic'} grid={cfg.resolution} deg period={cfg.period}")
    if real:
        return real_pipeline(cfg, datasets, only=only, force=args.force, jobs=args.jobs,
                             skip_overlays=args.skip_overlays, dry_run=args.dry_run)
    return synthetic_pipeline(cfg, datasets, only=only, force=args.force, jobs=args.jobs,
                              skip_overlays=args.skip_overlays)


if __name__ == "__main__":
    raise SystemExit(main())
