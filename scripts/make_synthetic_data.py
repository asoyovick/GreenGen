#!/usr/bin/env python3
"""Generate clearly fake monthly cubes for offline development and demos.

The synthetic data are NOT observations. They contain a seasonal cycle, noise,
planted trends, an adjacent pair of regions with opposite vegetation and
precipitation trends, and NaN cells where a variable does not apply (NDVI over
ocean). Outputs carry synthetic=true and a loud source attribute.

The default grid and period match config/app.yaml so the full pipeline and app
can run end to end without NASA access.
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import xarray as xr
import yaml
from PIL import Image, ImageDraw

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from src.common.config import load_app_config  # noqa: E402

LAND_GEOJSON = REPO_ROOT / "assets" / "ne_110m_land.geojson"
SOURCE_NOTE = (
    "SYNTHETIC DEMO DATA generated by scripts/make_synthetic_data.py. "
    "Not real observations. Do not cite as NASA data."
)


def target_lat_lon(res: float) -> tuple[np.ndarray, np.ndarray]:
    lat = np.arange(-90 + res / 2, 90, res)
    lon = np.arange(-180 + res / 2, 180, res)
    return lat, lon


def _unwrap_ring(ring: list[list[float]]) -> np.ndarray:
    """Unwrap a lon/lat ring so antimeridian crossings do not draw across Earth."""
    arr = np.asarray(ring, dtype=float)
    if len(arr) == 0:
        return arr
    lon = arr[:, 0].copy()
    for i in range(1, len(lon)):
        while lon[i] - lon[i - 1] > 180:
            lon[i] -= 360
        while lon[i] - lon[i - 1] < -180:
            lon[i] += 360
    return np.column_stack([lon, arr[:, 1]])


def _ring_for_drawing(ring: list[list[float]]) -> np.ndarray:
    """Prepare a lon/lat ring for PIL.

    Ordinary rings are unwrapped across the antimeridian. Antarctica's ring
    includes the south pole and already spans -180..180, so unwrapping it would
    make it self-intersect; keep its original coordinates.
    """
    arr = np.asarray(ring, dtype=float)
    if len(arr) == 0:
        return arr
    if arr[:, 1].min() <= -89.0:
        return arr
    return _unwrap_ring(ring)


def land_mask(lat: np.ndarray, lon: np.ndarray, res: float | None = None) -> np.ndarray:
    """Rasterize Natural Earth 110m land polygons onto the requested cell centres.

    Uses PIL so the synthetic generator has no GDAL/shapely dependency. The
    Natural Earth file is public domain and is used only for land/ocean
    applicability; it is not climate data.
    """
    if res is None:
        res = float(abs(lat[1] - lat[0])) if len(lat) > 1 else 0.5
    nx = len(lon)
    ny = len(lat)
    # Pixel coordinates use cell edges; extend by one pixel for safe clipping.
    x0, x1 = float(lon.min()) - res / 2, float(lon.max()) + res / 2
    y0, y1 = float(lat.max()) + res / 2, float(lat.min()) - res / 2
    width = max(1, int(round((x1 - x0) / res)))
    height = max(1, int(round((y0 - y1) / res)))
    img = Image.new("L", (width, height), 0)
    draw = ImageDraw.Draw(img)

    with LAND_GEOJSON.open("r", encoding="utf-8") as fh:
        geo = json.load(fh)

    for feature in geo.get("features", []):
        geom = feature.get("geometry") or {}
        if geom.get("type") == "Polygon":
            polygons = [geom.get("coordinates", [])]
        elif geom.get("type") == "MultiPolygon":
            polygons = geom.get("coordinates", [])
        else:
            continue
        for poly in polygons:
            if not poly:
                continue
            exterior = _ring_for_drawing(poly[0])
            holes = [_ring_for_drawing(r) for r in poly[1:] if len(r) >= 3]
            # Draw shifted copies so polygons crossing the antimeridian fill both sides.
            for shift in (-360.0, 0.0, 360.0):
                ext = exterior.copy()
                ext[:, 0] += shift
                if ext[:, 0].max() < x0 - res or ext[:, 0].min() > x1 + res:
                    continue
                pts = [((x - x0) / res, (y0 - y) / res) for x, y in ext]
                if len(pts) >= 3:
                    draw.polygon(pts, fill=1)
                for hole in holes:
                    h = hole.copy()
                    h[:, 0] += shift
                    hpts = [((x - x0) / res, (y0 - y) / res) for x, y in h]
                    if len(hpts) >= 3:
                        draw.polygon(hpts, fill=0)

    raster = np.asarray(img, dtype=np.uint8)
    # Sample at cell centres. Cell index j maps to lon index; row i maps to lat.
    iy = np.clip(np.round((y0 - lat) / res - 0.5).astype(int), 0, height - 1)
    ix = np.clip(np.round((lon - x0) / res - 0.5).astype(int), 0, width - 1)
    mask = raster[np.ix_(iy, ix)].astype(bool)
    return mask


def _in_box(lat2d: np.ndarray, lon2d: np.ndarray, box: dict | None) -> np.ndarray:
    if not box:
        return np.zeros_like(lat2d, dtype=bool)
    la0, la1 = box["lat"]
    lo0, lo1 = box["lon"]
    return (lat2d >= la0) & (lat2d <= la1) & (lon2d >= lo0) & (lon2d <= lo1)


def _seasonal(month: np.ndarray, lat2d: np.ndarray, amplitude: float, phase_month: float) -> np.ndarray:
    """Broadcast a month-of-year seasonal cycle to (time, lat, lon)."""
    phase = np.where(lat2d < 0, phase_month + 6.0, phase_month)
    return amplitude * np.cos(2 * np.pi * (month[:, None, None] - phase[None, :, :]) / 12.0)


def generate_cube(
    variable: str,
    cfg,
    *,
    lat: np.ndarray | None = None,
    lon: np.ndarray | None = None,
    times: pd.DatetimeIndex | None = None,
    seed: int = 20020101,
) -> xr.DataArray:
    """Build one deterministic synthetic cube with known planted trends."""
    res = cfg.resolution
    if lat is None or lon is None:
        lat, lon = target_lat_lon(res)
    if times is None:
        start, end = cfg.period
        times = pd.date_range(pd.Timestamp(start + "-01"), pd.Timestamp(end + "-01"), freq="MS")
    rng = np.random.default_rng(seed + sum(ord(c) for c in variable))

    lat2d, lon2d = np.meshgrid(lat, lon, indexing="ij")
    month = times.month.to_numpy()
    year_offset = np.array([(t.year - times[0].year) + (t.month - times[0].month) / 12.0 for t in times])
    land = land_mask(lat, lon, res)
    plant = cfg.raw["synthetic"]["planted_trends"][variable]
    noise_sigma = float(cfg.raw["synthetic"]["noise"][variable])

    if variable == "precipitation":
        baseline = 35.0 + 55.0 * np.cos(np.deg2rad(lat2d * 1.4)) ** 2
        seasonal = _seasonal(month, lat2d, 18.0, 7.0) * (0.5 + 0.5 * np.cos(np.deg2rad(lat2d)))
        data = baseline[None, :, :] + seasonal
        trend = np.full_like(lat2d, 0.02)
        trend += _in_box(lat2d, lon2d, plant["increasing_box"]) * plant["rate_per_year"]
        trend -= _in_box(lat2d, lon2d, plant["decreasing_box"]) * plant["rate_per_year"]
        data = data + trend[None, :, :] * year_offset[:, None, None]
        data = data + rng.normal(0, noise_sigma, size=data.shape)
        data = np.maximum(data, 0.0)
    elif variable == "vegetation":
        baseline = 0.20 + 0.45 * np.exp(-((lat2d - 3.0) / 28.0) ** 2)
        seasonal = _seasonal(month, lat2d, 0.12, 4.0)
        data = baseline[None, :, :] + seasonal
        trend = np.zeros_like(lat2d)
        trend += _in_box(lat2d, lon2d, plant["increasing_box"]) * plant["rate_per_year"]
        trend -= _in_box(lat2d, lon2d, plant["decreasing_box"]) * plant["rate_per_year"]
        data = data + trend[None, :, :] * year_offset[:, None, None]
        data = data + rng.normal(0, noise_sigma, size=data.shape)
        data = np.clip(data, -0.2, 1.0)
        data = np.where(land[None, :, :], data, np.nan)
    elif variable == "temperature":
        baseline = 30.0 - 0.55 * np.abs(lat2d)
        amplitude = 2.0 + 12.0 * (np.abs(lat2d) / 90.0)
        seasonal = _seasonal(month, lat2d, 1.0, 7.0) * amplitude[None, :, :]
        trend = np.full_like(lat2d, 0.02)
        trend += _in_box(lat2d, lon2d, plant["increasing_box"]) * plant["rate_per_year"]
        data = baseline[None, :, :] + seasonal
        data = data + trend[None, :, :] * year_offset[:, None, None]
        data = data + rng.normal(0, noise_sigma, size=data.shape)
    else:
        raise ValueError(f"No synthetic generator for variable {variable!r}")

    da = xr.DataArray(
        data.astype("float32"),
        coords={"time": times, "lat": lat.astype("float32"), "lon": lon.astype("float32")},
        dims=("time", "lat", "lon"),
        name=variable,
    )
    meta = cfg.variables[variable]
    da.attrs.update(
        {
            "units": meta["unit"],
            "display_name": meta["display_name"],
            "surface": ",".join(meta["surface"]),
            "model_based": bool(meta["model_based"]),
            "synthetic": True,
            "source": SOURCE_NOTE,
            "planted_trend_units": f"{meta['unit']} per year",
        }
    )
    return da


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--config", default=str(REPO_ROOT / "config" / "app.yaml"))
    ap.add_argument("--out", default=None, help="Output directory (default: config data/synthetic)")
    ap.add_argument("--seed", type=int, default=20020101)
    ap.add_argument("--lat-range", nargs=2, type=float, default=None, metavar=("LAT0", "LAT1"))
    ap.add_argument("--lon-range", nargs=2, type=float, default=None, metavar=("LON0", "LON1"))
    ap.add_argument("--start", default=None, help="YYYY-MM, for quick tests")
    ap.add_argument("--end", default=None, help="YYYY-MM, for quick tests")
    args = ap.parse_args()

    cfg = load_app_config(args.config)
    out = Path(args.out) if args.out else cfg.data_dir("synthetic")
    out.mkdir(parents=True, exist_ok=True)

    res = cfg.resolution
    full_lat, full_lon = target_lat_lon(res)
    if args.lat_range:
        lat = full_lat[(full_lat >= args.lat_range[0]) & (full_lat <= args.lat_range[1])]
    else:
        lat = full_lat
    if args.lon_range:
        lon = full_lon[(full_lon >= args.lon_range[0]) & (full_lon <= args.lon_range[1])]
    else:
        lon = full_lon
    if len(lat) < 2 or len(lon) < 2:
        sys.exit("Latitude/longitude subset has fewer than 2 cells; widen the range.")

    start = args.start or cfg.period[0]
    end = args.end or cfg.period[1]
    times = pd.date_range(pd.Timestamp(start + "-01"), pd.Timestamp(end + "-01"), freq="MS")
    if len(times) < 12:
        sys.exit("Synthetic period must cover at least 12 months.")

    written = []
    for variable in cfg.mode_variables("synthetic"):
        da = generate_cube(variable, cfg, lat=lat, lon=lon, times=times, seed=args.seed)
        path = out / f"{variable}.zarr"
        da.to_dataset().to_zarr(path, mode="w")
        frac_nan = float(np.isnan(da.values).mean())
        print(
            f"{variable:14s} {da.shape}  range=[{float(da.min()):.3g}, {float(da.max()):.3g}] "
            f"{da.attrs['units']}  NaN={frac_nan:.1%}  -> {path}"
        )
        written.append(str(path))

    manifest = {
        "mode": "synthetic",
        "synthetic": True,
        "warning": SOURCE_NOTE,
        "generated_at_utc": dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds"),
        "seed": args.seed,
        "grid": {"resolution_deg": res, "n_lat": int(len(lat)), "n_lon": int(len(lon))},
        "period": {"start": str(times[0].date()), "end": str(times[-1].date()), "n_months": int(len(times))},
        "variables": cfg.mode_variables("synthetic"),
        "planted_trends": cfg.raw["synthetic"]["planted_trends"],
        "land_mask_source": "Natural Earth 1:110m land (public domain), assets/ne_110m_land.geojson",
        "files": written,
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2), encoding="utf-8")
    print(f"Wrote {len(written)} synthetic cubes and {out / 'manifest.json'}")
    print("SYNTHETIC DEMO DATA, not real observations.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
