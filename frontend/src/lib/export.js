import {
  NOT_A_FORECAST,
  SYNTHETIC_WARNING,
  formatCoord,
  formatRate,
  nearbyText,
  periodText,
  verdictText,
  downloadText,
} from "./format.js";

function safeName(value) {
  return String(value).replace(/[^a-z0-9._-]+/gi, "-").replace(/^-+|-+$/g, "");
}

export function reportFilename(report, extension) {
  const lat = report?.cell?.lat ?? report?.query?.lat ?? 0;
  const lon = report?.cell?.lon ?? report?.query?.lon ?? 0;
  const ns = lat >= 0 ? "N" : "S";
  const ew = lon >= 0 ? "E" : "W";
  return safeName(
    `global-change-report-${Math.abs(lat).toFixed(1)}${ns}-${Math.abs(lon).toFixed(1)}${ew}.${extension}`,
  );
}

export function reportToMarkdown(report, meta = {}) {
  if (!report) return "";
  const lines = [];
  const mode = report.mode || meta.mode || "unknown";
  lines.push("# Global Change Explorer report");
  lines.push("");
  if (report.synthetic || mode === "synthetic") {
    lines.push(`> **${SYNTHETIC_WARNING}**`);
    lines.push("");
  }
  const cell = report.cell || {};
  lines.push(`**Location:** ${formatCoord(cell.lat, cell.lon)} (nearest 0.5° grid cell)`);
  lines.push(`**Query:** ${formatCoord(report.query?.lat, report.query?.lon)}`);
  lines.push(`**Mode:** ${mode}`);
  if (report.period) lines.push(`**Period:** ${periodText(report.period)}`);
  lines.push(`**Grid:** 0.5° (about 55 km at the equator)`);
  lines.push("");
  if (report.summary) {
    lines.push("## Summary");
    lines.push("");
    lines.push(report.summary);
    lines.push("");
  }
  lines.push("## Variables");
  lines.push("");
  if (!report.variables?.length) {
    lines.push("No variables apply at this location in the loaded layer set.");
  } else {
    for (const row of report.variables) {
      const flags = [];
      if (row.significant) flags.push("FDR-corrected significant");
      if (row.model_based) flags.push("model-based");
      if (row.low_confidence) flags.push("low confidence");
      lines.push(`### ${row.variable}`);
      lines.push("");
      lines.push(`- Verdict: **${verdictText(row)}**`);
      lines.push(`- Rate: ${formatRate(row.rate_per_decade, row.unit)}`);
      lines.push(`- Years used: ${row.n_years}`);
      if (flags.length) lines.push(`- Flags: ${flags.join(", ")}`);
      if (row.nearby) lines.push(`- Nearby: ${nearbyText(row.nearby)}`);
      if (row.period) lines.push(`- Dataset period: ${periodText(row.period)}`);
      if (row.source_dataset) {
        const version = row.dataset_version ? ` v${row.dataset_version}` : "";
        lines.push(`- Source dataset: ${row.source_dataset}${version}`);
      }
      lines.push("");
    }
  }
  lines.push("## How to read this");
  lines.push("");
  lines.push(
    "- Rates are Theil–Sen slopes of annual anomalies, expressed per decade.",
    "- Significance uses the Mann–Kendall test with Benjamini–Hochberg FDR correction across grid cells at α = 0.05.",
    "- “No significant change detected” does not mean nothing changed; it means the evidence was not strong enough.",
    `- ${NOT_A_FORECAST}`,
  );
  lines.push("");
  if (report.surface_inferred) {
    lines.push(`Surface note: ${report.surface_inferred.explanation}`);
    lines.push("");
  }
  if (report.generated_at_utc) {
    lines.push(`Layer generated: ${report.generated_at_utc}`);
  }
  lines.push("Generated by Global Change Explorer. See docs/LIMITATIONS.md and docs/DATA_SOURCES.md.");
  lines.push("");
  return lines.join("\n");
}

export function exportReportJson(report) {
  downloadText(
    reportFilename(report, "json"),
    JSON.stringify(report, null, 2),
    "application/json;charset=utf-8",
  );
}

export function exportReportMarkdown(report) {
  downloadText(
    reportFilename(report, "md"),
    reportToMarkdown(report),
    "text/markdown;charset=utf-8",
  );
}

export async function copyText(text) {
  if (navigator.clipboard?.writeText) {
    await navigator.clipboard.writeText(text);
    return true;
  }
  const area = document.createElement("textarea");
  area.value = text;
  area.setAttribute("readonly", "");
  area.style.position = "fixed";
  area.style.opacity = "0";
  document.body.appendChild(area);
  area.select();
  const ok = document.execCommand("copy");
  area.remove();
  return ok;
}

export function shareUrl(lat, lon, layer) {
  const url = new URL(window.location.href);
  url.search = "";
  url.searchParams.set("lat", Number(lat).toFixed(4));
  url.searchParams.set("lon", Number(lon).toFixed(4));
  if (layer) url.searchParams.set("layer", layer);
  return url.toString();
}
